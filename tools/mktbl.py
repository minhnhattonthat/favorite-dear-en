"""mktbl.py: write tbl/jp.tbl from the font (kanji by bitmap match, everything else from the hand-read layout).

    python -X utf8 tools/mktbl.py work/disc/tree/PSX.EXE tbl/jp.tbl

Codes are 16-bit LE font cells, so table keys are two bytes (`2400=あ` is code 0x0024). Layout read from a zoomed,
labelled sheet (docs/re/text.md §Encoding); kanji cells take fontmatch.py's exact MS Gothic match, with the few
cells the game drew differently fixed by eye below (KANJI_FIX). Run once; the table is then a hand-edited source.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

PUNCT = "、。・：？！々ー～“”（）｛｝「」『』－＄"  # 0x001-0x015; 0x5CD-0x5E0 repeat the first 20
HIRA = [chr(c) for c in range(0x3041, 0x3094) if chr(c) not in "ぢゎゐゑ"]  # 0x023-0x071
KATA = [chr(c) for c in range(0x30A1, 0x30F4) if chr(c) not in "ヂヅヌユヲヮヰヱ"] + ["ヴ"]  # 0x072-0x0BD
UPPER = [c for c in "ＡＢＣＤＥＦＧＨＩＪＬＭＮＰＱＲＳＴＵＶＷＹＺ"]  # 0x57D-0x593 (Ｋ Ｏ Ｘ are 0x020-0x022)
LOWER = [chr(c) for c in range(0xFF41, 0xFF5B)]  # 0x594-0x5AD
KANJI_FIX = {0x0D8: "違", 0x0EA: "噂", 0x148: "割", 0x2B1: "種", 0x2CA: "重", 0x3B5: "樽", 0x511: "優",
             0x535: "覧", 0x183: "犠", 0x56F: "壺", 0x5E8: "￥", 0x5FA: "貝", 0x629: "蝕", 0x60E: "喰"}
DUP_LO = 0x5CD  # second punctuation set 0x5CD-0x5E0; the first (0x001-0x014) is written with stand-ins
NDUP = 20
# stand-ins avoid { } [ ], which tbl.py reads as control/hex tokens
ALT = dict(zip("、。・：？！々ー～“”（）｛｝「」『』－", "､｡･:?!〻ｰ~\"'()〔〕｢｣《》-"))
BLANK = {0x5E9: "〿"}  # empty cell between 湾 and 史, used once in the script as a space


def layout():
    m = {0x000: "　"}
    for i, ch in enumerate(PUNCT):
        m[0x001 + i] = ch
    for i in range(10):
        m[0x016 + i] = chr(0xFF10 + i)
    m.update({0x020: "Ｋ", 0x021: "Ｏ", 0x022: "Ｘ"})
    for i, ch in enumerate(HIRA):
        m[0x023 + i] = ch
    for i, ch in enumerate(KATA):
        m[0x072 + i] = ch
    m.update({0x57B: "，", 0x57C: "．"})
    for i, ch in enumerate(UPPER):
        m[0x57D + i] = ch
    for i, ch in enumerate(LOWER):
        m[0x594 + i] = ch
    for i, ch in enumerate("ぢヌユヲヂヅ②"):
        m[0x5AE + i] = ch
    m.update({0x5BF: "③", 0x5CC: "④"})
    m.update(BLANK)
    for i, ch in enumerate(PUNCT[:NDUP]):
        m[DUP_LO + i] = ch
    return m


def main():
    from fontmatch import match
    exe = open(sys.argv[1], "rb").read()
    _, res = match(exe)
    m = layout()
    for c, ch, *_ in res:
        if c not in m and ch and c not in BLANK:
            m[c] = KANJI_FIX.get(c, ch)
    # the dialogue uses the 0x5CD set; give the 0x001 set distinct stand-ins so encode(decode()) stays exact
    for c in range(0x001, 0x001 + NDUP):
        m[c] = ALT[m[c]]
    vals = list(m.values())
    dup = {v for v in vals if vals.count(v) > 1}
    assert not dup, dup
    lines = ["# Favorite Dear: 16-bit LE font-cell codes (key bytes = code low, high). Generated by tools/mktbl.py,",
             "# then hand-edited. 0x001-0x014 duplicate 0x5CD-0x5E0 and decode as stand-ins (､｡･ etc.).",
             "# Control codes from the text printer at 0x800FC270 (args are halfwords; other FFxx are skipped).",
             "FEFF={n}", "FCFF={wait}", "FFFF={end}", "00FF={ff00:2}", "10FF={speed:2}", "90FF={num:4}",
             "FDFF={fffd}", "FBFF={fffb}"]
    for c in sorted(m):
        lines.append(f"{c & 0xFF:02X}{c >> 8:02X}={m[c]}")
    Path(sys.argv[2]).parent.mkdir(exist_ok=True)
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(m), "codes")


if __name__ == "__main__":
    main()
